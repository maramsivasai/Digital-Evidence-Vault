import PDFDocument from "pdfkit";

const formatDate = (value) => {
  if (!value) return "Not available";

  return new Date(value).toLocaleString();
};

export const generateReportPDF = (report) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margin: 50,
        bufferPages: true
      });

      const chunks = [];

      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      doc.fontSize(20).text("DIGITAL EVIDENCE VAULT", {
        align: "center"
      });

      doc.moveDown(0.5);

      doc.fontSize(16).text(report.reportType, {
        align: "center"
      });

      doc.moveDown();

      doc.fontSize(10);
      doc.text(`Generated At: ${formatDate(report.generatedAt)}`);
      doc.text(`Generated By: ${report.generatedBy.name}`);
      doc.text(`Report Reference: ${report.reference}`);

      doc.moveDown();
      doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke();
      doc.moveDown();

      for (const section of report.sections) {
        doc.fontSize(13).text(section.heading, {
          underline: true
        });

        doc.moveDown(0.4);
        doc.fontSize(10);

        for (const item of section.items) {
          const value =
            item.value === undefined || item.value === null
              ? "Not available"
              : String(item.value);

          doc.text(`${item.label}: ${value}`, {
            indent: 10
          });
        }

        if (section.items.length === 0) {
          doc.text("No records available.", { indent: 10 });
        }

        doc.moveDown();
      }

      doc.moveDown();
      doc.fontSize(8).text(
        "This report contains information retrieved from the Digital Evidence Vault. " +
        "It does not independently establish the authenticity or legal admissibility of evidence.",
        { align: "center" }
      );

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};